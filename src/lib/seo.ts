import type { Metadata } from "next";
import type { PortfolioLang } from "./portfolio-content";

export const SITE_URL = "https://mahmud-alhussen.de";
export const SITE_NAME = "Mahmud Al Hussen";

type LangPaths = Partial<Record<PortfolioLang, string>>;

// Canonical URL, hreflang alternates and Open Graph for one page. Paths are relative to
// metadataBase (SITE_URL). German is x-default: the site targets roles in the DACH region.
export function pageMetadata({
  lang,
  paths,
  title,
  description,
}: {
  lang: PortfolioLang;
  paths: LangPaths;
  title: string;
  description?: string;
}): Metadata {
  const languages: Record<string, string> = {};
  if (paths.de) languages.de = paths.de;
  if (paths.en) languages.en = paths.en;
  if (paths.de) languages["x-default"] = paths.de;

  return {
    title,
    description,
    alternates: { canonical: paths[lang], languages },
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      title,
      description,
      url: paths[lang],
      locale: lang === "de" ? "de_DE" : "en_US",
      // A page's openGraph replaces the inherited one completely, including the image
      // generated by app/[locale]/opengraph-image.tsx, so it is referenced explicitly.
      images: [{ url: `/${lang}/opengraph-image`, width: 1200, height: 630, alt: SITE_NAME }],
    },
  };
}
